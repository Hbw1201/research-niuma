// Check the actual app.asar, then exercise the bundled runtime with empty state.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync, spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const asar = require('@electron/asar');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const macFolder = process.arch === 'arm64' ? 'mac-arm64' : 'mac';
const bundle = process.platform === 'darwin' ? path.join(root, 'release', macFolder, 'Relay Lab.app', 'Contents') : path.join(root, 'release', process.platform === 'win32' ? 'win-unpacked' : 'linux-unpacked');
const archive = path.join(bundle, process.platform === 'darwin' ? 'Resources' : 'resources', 'app.asar');
const executable = path.join(bundle, ...(process.platform === 'darwin' ? ['MacOS', 'Relay Lab'] : [process.platform === 'win32' ? 'Relay Lab.exe' : 'relay-lab']));
const git = args => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const tracked = git(['ls-files', '-z']).split('\0');
const expected = tracked.filter(f => /^(bin|src|public|desktop)\//.test(f));
const found = new Set();
const manifest = [];
for (const entry of asar.listPackage(archive)) {
  const file = entry.replaceAll('\\', '/').replace(/^\//, '');
  const stat = asar.statFile(archive, file);
  if (stat.files) continue;
  if (stat.link || stat.unpacked) throw new Error('Unexpected linked or unpacked app file: ' + file);
  if (file !== 'package.json' && !expected.includes(file)) throw new Error('Unexpected app payload: ' + file);
  const bytes = asar.extractFile(archive, file);
  if (file === 'package.json') {
    const actual = JSON.parse(bytes);
    if (actual.name !== pkg.name || actual.version !== pkg.version || actual.main !== pkg.main) throw new Error('Packaged metadata mismatch.');
    for (const key of Object.keys(actual)) if (!(key in pkg) && key !== '_name' && key !== '_version') throw new Error('Unexpected packaged metadata field: ' + key);
  } else if (!bytes.equals(fs.readFileSync(path.join(root, file)))) throw new Error('Packaged source differs: ' + file);
  found.add(file);
  manifest.push({ file, sha256: hash(bytes), bytes: bytes.length });
}
for (const file of [...expected, 'package.json']) if (!found.has(file)) throw new Error('Missing packaged file: ' + file);
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'niuma-release-'));
const workspace = path.join(temp, 'workspace');
const env = { ...process.env, ELECTRON_RUN_AS_NODE: '1', HOME: temp, USERPROFILE: temp, CODEX_HOME: path.join(temp, '.codex'), CLAUDE_CONFIG_DIR: path.join(temp, '.claude') };
for (const key of Object.keys(env)) if (/^(?:ANTHROPIC_|OPENAI_|GH_TOKEN$|GITHUB_TOKEN$)/.test(key)) delete env[key];
const cli = path.join(archive, 'bin', 'relay-lab.mjs');
const help = execFileSync(executable, [cli, '--help'], { env, encoding: 'utf8', timeout: 30000 });
if (!help.includes('v' + pkg.version)) throw new Error('Bundled CLI version check failed.');
const child = spawn(executable, [cli, 'start', '--workspace', workspace, '--port', '0'], { env, stdio: ['ignore', 'pipe', 'pipe'] });
let failed = false;
child.on('error', () => { failed = true; });
child.stdout.resume(); child.stderr.resume();
try {
  let connected = false;
  for (let attempt = 0; attempt < 60; attempt++) {
    if (failed || child.exitCode !== null) throw new Error('Bundled server exited before becoming ready.');
    const connection = path.join(workspace, '.relay-lab', 'connection.json');
    if (fs.existsSync(connection)) {
      const { url } = JSON.parse(fs.readFileSync(connection));
      const state = await fetch(url + '/api/state').then(r => r.json());
      const html = await fetch(url).then(r => r.text());
      if (state.version !== pkg.version || state.projects.length !== 0 || !html.includes('科研牛马局')) throw new Error('Fresh packaged service check failed.');
      connected = true; break;
    }
    await new Promise(resolve => setTimeout(resolve, 500));
  }
  if (!connected) throw new Error('Bundled service timed out.');
} finally {
  child.kill();
  await new Promise(resolve => { if (child.exitCode !== null) resolve(); else { child.once('exit', resolve); setTimeout(resolve, 5000).unref(); } });
  // This directory is newly generated by this process, never a user's workspace.
  fs.rmSync(temp, { recursive: true, force: true });
}
const report = { version: pkg.version, commit: git(['rev-parse', 'HEAD']), platform: process.platform, arch: process.arch, appAsarSha256: hash(fs.readFileSync(archive)), fileCount: manifest.length, files: manifest, checks: { sourceMatches: true, bundledCli: true, freshLocalService: true, noInitialProjects: true }, desktopGuiTested: false };
fs.writeFileSync(path.join(root, 'release', `audit-${process.platform}-${process.arch}.json`), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ platform: process.platform, arch: process.arch, fileCount: manifest.length, checks: report.checks }));
